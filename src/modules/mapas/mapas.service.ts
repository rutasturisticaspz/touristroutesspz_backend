import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { config } from '../../config';
import { HttpError, noEncontrado, solicitudInvalida } from '../../lib/errors';

// Downloadable maps.
// They have no table: they are stored in a JSON file inside the
// uploads folder, which is already a persistent volume. This way
// adding maps does not require touching the database schema. Each map
// is just a name and the link of the file on Google Drive; the file
// itself never goes through the server.

const ARCHIVO = path.join(config.uploads.directorio, 'mapas.json');
const SERVIDORES_PERMITIDOS = new Set(['drive.google.com', 'docs.google.com']);
const ANCHO_MINIATURA = 800;

interface MapaGuardado {
  id: string;
  nombre: string;
  enlace: string;
  createdAt: string;
}

export interface Mapa extends MapaGuardado {
  // Preview generated by Drive. null if the link is not for a file.
  miniatura: string | null;
}

// Writes are queued: two administrators saving at the same time must
// not step on each other by reading the same state.
let cola: Promise<unknown> = Promise.resolve();

function enSerie<T>(tarea: () => Promise<T>): Promise<T> {
  const resultado = cola.then(tarea);
  cola = resultado.catch(() => undefined);
  return resultado;
}

function esUrl(texto: string): boolean {
  try {
    new URL(texto);
    return true;
  } catch {
    return false;
  }
}

function esMapaGuardado(valor: unknown): valor is MapaGuardado {
  if (typeof valor !== 'object' || valor === null) return false;
  const { id, nombre, enlace, createdAt } = valor as Record<string, unknown>;
  return (
    typeof id === 'string' &&
    typeof nombre === 'string' &&
    typeof enlace === 'string' &&
    esUrl(enlace) &&
    typeof createdAt === 'string'
  );
}

const archivoDanado = () =>
  new HttpError(500, 'El archivo de mapas está dañado. Revise o elimine mapas.json en uploads.');

// A missing file is an empty list. A file that is not valid JSON, is not
// an array or has malformed entries is reported as damaged instead of
// being trusted: it is never silently replaced, because the next write
// would wipe whatever the person was trying to recover.
async function leerArchivo(): Promise<MapaGuardado[]> {
  let contenido: string;
  try {
    contenido = await readFile(ARCHIVO, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }

  let datos: unknown;
  try {
    datos = JSON.parse(contenido);
  } catch {
    throw archivoDanado();
  }
  if (!Array.isArray(datos) || !datos.every(esMapaGuardado)) throw archivoDanado();
  return datos;
}

async function guardarArchivo(mapas: MapaGuardado[]): Promise<void> {
  await mkdir(config.uploads.directorio, { recursive: true });
  const temporal = `${ARCHIVO}.${process.pid}.tmp`;
  await writeFile(temporal, JSON.stringify(mapas, null, 2), 'utf8');
  await rename(temporal, ARCHIVO);
}

// Accepts only https Google Drive links and returns the clean link.
export function validarEnlaceDrive(texto: string): string {
  let url: URL;
  try {
    url = new URL(texto.trim());
  } catch {
    throw solicitudInvalida('El enlace no es una dirección válida');
  }
  if (url.protocol !== 'https:' || !SERVIDORES_PERMITIDOS.has(url.hostname)) {
    throw solicitudInvalida('El enlace debe ser de Google Drive (https://drive.google.com/…)');
  }
  return url.toString();
}

// For /file/d/<id>/view and /open?id=<id>. Folders have no thumbnail.
function idDeArchivo(enlace: string): string | null {
  const url = new URL(enlace);
  const enRuta = url.pathname.match(/\/file\/d\/([\w-]+)/);
  if (enRuta) return enRuta[1];
  if (url.pathname.startsWith('/open')) return url.searchParams.get('id');
  return null;
}

function darFormato(mapa: MapaGuardado): Mapa {
  const id = idDeArchivo(mapa.enlace);
  return {
    ...mapa,
    miniatura: id
      ? `https://drive.google.com/thumbnail?id=${encodeURIComponent(id)}&sz=w${ANCHO_MINIATURA}`
      : null,
  };
}

export const mapasService = {
  // The public list never fails because of a damaged file: it shows no
  // maps and logs the problem. Writes do fail, so nothing is overwritten.
  async listar() {
    let mapas: MapaGuardado[] = [];
    try {
      mapas = await leerArchivo();
    } catch (error) {
      if (!(error instanceof HttpError)) throw error;
      console.error(error.message);
    }
    return { total: mapas.length, datos: mapas.map(darFormato) };
  },

  crear(datos: { nombre: string; enlace: string }) {
    const enlace = validarEnlaceDrive(datos.enlace);
    return enSerie(async () => {
      const mapas = await leerArchivo();
      const nuevo: MapaGuardado = {
        id: randomUUID(),
        nombre: datos.nombre.trim(),
        enlace,
        createdAt: new Date().toISOString(),
      };
      await guardarArchivo([...mapas, nuevo]);
      return darFormato(nuevo);
    });
  },

  actualizar(id: string, datos: { nombre?: string; enlace?: string }) {
    const enlace = datos.enlace === undefined ? undefined : validarEnlaceDrive(datos.enlace);
    return enSerie(async () => {
      const mapas = await leerArchivo();
      const actual = mapas.find((mapa) => mapa.id === id);
      if (!actual) throw noEncontrado('Mapa');

      const actualizado: MapaGuardado = {
        ...actual,
        nombre: datos.nombre?.trim() ?? actual.nombre,
        enlace: enlace ?? actual.enlace,
      };
      await guardarArchivo(mapas.map((mapa) => (mapa.id === id ? actualizado : mapa)));
      return darFormato(actualizado);
    });
  },

  eliminar(id: string) {
    return enSerie(async () => {
      const mapas = await leerArchivo();
      if (!mapas.some((mapa) => mapa.id === id)) throw noEncontrado('Mapa');
      await guardarArchivo(mapas.filter((mapa) => mapa.id !== id));
      return { ok: true };
    });
  },
};
